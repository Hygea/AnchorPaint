import { describe, it } from 'node:test';
import { expect } from '@playwright/test';
import { strFromU8, strToU8, zipSync, unzipSync } from 'fflate';
import { readBambuProfile } from '../src/export/profile';
import { exportBambu3mf } from '../src/export/bambu-3mf';
import { fixtureMesh } from './fixtures';
import { settingsProject } from './settings-project';
import { readFileSync } from 'node:fs';

describe('explicit local Bambu settings source', () => {
  it('bundles stock single-filament settings without model, cache or account data', () => {
    const bytes = readFileSync('src/assets/default-bambu-settings.3mf');
    expect(Object.keys(unzipSync(bytes)).sort()).toEqual(['3D/3dmodel.model', 'Metadata/project_settings.config']);
    const profile = readBambuProfile(bytes);
    expect(profile.printer).toBe('Bambu Lab P1S');
    const settings = JSON.parse(strFromU8(profile.files['Metadata/project_settings.config']));
    expect(settings.printer_settings_id).toBe('Bambu Lab P1S 0.4 nozzle');
    expect(settings.filament_settings_id).toEqual(['Bambu PLA Basic @BBL P1S 0.4 nozzle']);
    expect(settings.wall_loops).toBe('2');
    expect(settings.printable_area).toEqual(['0x0', '256x0', '256x256', '0x256']);
    expect(settings.printer_notes).toBe('');
    expect(strFromU8(profile.files['Metadata/project_settings.config'])).not.toMatch(/C:\\\\Users|Fixedprimeline|access_token|device_id/);
    const output = unzipSync(exportBambu3mf({ name: 'Default', model: fixtureMesh('single_boss.stl'),
      modifiers: [{ name: 'Anchor', mesh: fixtureMesh('single_boss_modifier_01.stl'), wallLoops: 4 }], profile }));
    expect(strFromU8(output['Metadata/model_settings.config'])).toContain('key="wall_loops" value="4"');
  });
  it('copies only settings and drops source geometry, painting and cached toolpaths', () => {
    const input = settingsProject({ 'Metadata/plate_1.gcode': strToU8('do not copy'), 'private.txt': strToU8('do not copy'),
      'Metadata/machine_settings_1.config': strToU8('{"name":"test"}') });
    const profile = readBambuProfile(input);
    expect(Object.keys(profile.files).sort()).toEqual(['Metadata/machine_settings_1.config', 'Metadata/project_settings.config']);
    const output = unzipSync(exportBambu3mf({ name: 'Test', model: fixtureMesh('single_boss.stl'), modifiers: [], profile }));
    expect(output['Metadata/project_settings.config']).toEqual(profile.files['Metadata/project_settings.config']);
    expect(output['private.txt']).toBeUndefined();
    expect(output['Metadata/plate_1.gcode']).toBeUndefined();
    const model = strFromU8(output['3D/3dmodel.model']);
    expect(model).toContain('BambuStudio-02.08.02.61');
    expect(model).toContain('Generated by AnchorPaint');
    expect(model).toContain('<mesh>');
    expect(model).toContain('transform="1 0 0 0 1 0 0 0 1 100 100 0"');
    expect(strFromU8(output['Metadata/model_settings.config'])).toContain('<model_instance>');
  });
  it('requires a native saved project with actual printer and process choices', () => {
    expect(() => readBambuProfile(zipSync({}))).toThrow(/saved by Bambu/);
    expect(() => readBambuProfile(settingsProject({ 'Metadata/project_settings.config': strToU8('{}') }))).toThrow(/incomplete/);
    expect(() => readBambuProfile(settingsProject({ '3D/3dmodel.model': strToU8('<model><metadata name="Application">Other</metadata></model>') }))).toThrow(/native/);
  });
  it('rejects XML entity declarations and malformed settings', () => {
    expect(() => readBambuProfile(settingsProject({ '3D/3dmodel.model': strToU8('<!DOCTYPE model><model/>') }))).toThrow(/XML/);
    expect(() => readBambuProfile(settingsProject({ 'Metadata/project_settings.config': strToU8('not JSON') }))).toThrow();
  });
  it('rejects archive expansion above the settings-source limit', () => {
    const input = settingsProject({ 'Metadata/machine_settings_1.config': new Uint8Array(21 * 1024 * 1024) });
    expect(() => readBambuProfile(input)).toThrow(/20 MB/);
  });
  it('rejects a model that cannot fit the selected bed or overlaps exclusions', () => {
    const profile = readBambuProfile(settingsProject());
    const model = fixtureMesh('ten_bosses.stl');
    expect(() => exportBambu3mf({ name: 'Test', model, modifiers: [], profile: { ...profile, bed: { min: [0, 0], max: [50, 50] } } })).toThrow(/does not fit/);
    expect(() => exportBambu3mf({ name: 'Test', model, modifiers: [], profile: { ...profile, excluded: [{ min: [90, 90], max: [110, 110] }] } })).toThrow(/exclusion/);
  });
});
